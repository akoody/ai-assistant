async function initDatabase() {
  let client;

  try {
    console.log('🔌 Подключение к MongoDB...');
    client = new MongoClient(MONGODB_URI, {
      useUnifiedTopology: true,
      useNewUrlParser: true,
    });

    await client.connect();
    console.log('✅ Подключение установлено\n');

    const db = client.db(DB_NAME);

    // Инициализация настроек микросервиса
    const settingsCollection = db.collection('microserviceSettings');
    const existingConfig = await settingsCollection.findOne({
      serviceName: 'ai-slots',
    });

    if (existingConfig) {
      console.log('⚠️  Конфигурация для ai-slots уже существует\n');
      const update = process.env.FORCE_UPDATE === 'true' || false;

      if (update) {
        console.log('🔄 Обновление существующей конфигурации...');
        await settingsCollection.updateOne(
          { serviceName: 'ai-slots' },
          {
            $set: {
              ...defaultConfig,
              updatedAt: new Date(),
            },
          }
        );
        console.log('✅ Конфигурация обновлена\n');
      } else {
        console.log('ℹ️  Используйте FORCE_UPDATE=true для обновления конфигурации\n');
      }
    } else {
      console.log('📝 Создание новой конфигурации...');
      await settingsCollection.insertOne(defaultConfig);
      console.log('✅ Конфигурация создана\n');
    }

    // Инициализация слотов
    const slotsCollection = db.collection('slots');
    const existingSlots = await slotsCollection.find({}).toArray();

    if (existingSlots.length > 0) {
      console.log(`⚠️  В БД уже существует ${existingSlots.length} слотов\n`);
      const update = process.env.FORCE_UPDATE === 'true' || false;

      if (update) {
        console.log('🔄 Обновление слотов...');
        await slotsCollection.deleteMany({});
        await slotsCollection.insertMany(
          defaultSlots.map((slot) => ({
            ...slot,
            createdAt: new Date(),
            updatedAt: new Date(),
          }))
        );
        console.log(`✅ Создано ${defaultSlots.length} слотов\n`);
      } else {
        console.log('ℹ️  Используйте FORCE_UPDATE=true для обновления слотов\n');
      }
    } else {
      console.log('📝 Создание слотов...');
      await slotsCollection.insertMany(
        defaultSlots.map((slot) => ({
          ...slot,
          createdAt: new Date(),
          updatedAt: new Date(),
        }))
      );
      console.log(`✅ Создано ${defaultSlots.length} слотов\n`);
    }

    // Выводим итоговую информацию
    const finalConfig = await settingsCollection.findOne({
      serviceName: 'ai-slots',
    });
    const finalSlots = await slotsCollection.find({}).toArray();

    console.log('📋 Финальная конфигурация:');
    console.log(JSON.stringify(finalConfig, null, 2));
    console.log(`\n📋 Всего слотов в БД: ${finalSlots.length}`);
    finalSlots.forEach((slot, index) => {
      console.log(`  ${index + 1}. ${slot.name}: ${slot.description}`);
    });

    console.log('\n✅ Инициализация БД завершена успешно!');
  } catch (error) {
    console.error('❌ Ошибка при инициализации БД:', error);
    process.exit(1);
  } finally {
    if (client) {
      await client.close();
      console.log('\n🔌 Подключение закрыто');
    }
  }
}

initDatabase().catch((error) => {
  console.error('❌ Критическая ошибка:', error);
  process.exit(1);
});
