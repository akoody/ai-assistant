const NON_WORD_BOUNDARY = String.raw`[^\p{L}\p{N}_]`;

function wrapTokenPattern(source) {
  return new RegExp(`(?:^|${NON_WORD_BOUNDARY})(${source})(?=$|${NON_WORD_BOUNDARY})`, 'u');
}

function normalizeHintText(value = '') {
  return String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .trim();
}

