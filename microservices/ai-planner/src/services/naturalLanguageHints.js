const TIME_HINT_PATTERNS = [
  wrapTokenPattern('(?:утром|утро)'),
  wrapTokenPattern('(?:днем|дневное\\s+время|дневной\\s+сеанс)'),
  wrapTokenPattern('(?:вечером|вечер)'),
  wrapTokenPattern('(?:ночью|ночь)'),
  wrapTokenPattern('(?:любое\\s+время)'),
];

function extractHint(text, patterns) {
  const normalized = normalizeHintText(text);
  if (!normalized) {
    return '';
  }

  for (const pattern of patterns) {
    const match = normalized.match(pattern);
    if (match && match[1]) {
      return match[1].trim();
    }
  }

  return '';
}

export function extractDateHintFromText(text = '') {
  return extractHint(text, DATE_HINT_PATTERNS);
}

export function extractTimeHintFromText(text = '') {
  return extractHint(text, TIME_HINT_PATTERNS);
}

export function hasDateReferenceInText(text = '') {
  const normalized = normalizeHintText(text);
  if (!normalized) {
    return false;
  }

  return DATE_REFERENCE_PATTERNS.some((pattern) => pattern.test(normalized));
}
